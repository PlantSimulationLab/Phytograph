"""Put the phytograph agent guidance into a user's project.

An agent started in a project that uses phytograph reads that project's
``AGENTS.md`` (Codex, Cursor, Claude Code when there is no ``CLAUDE.md``) or
``CLAUDE.md`` (Claude Code). ``python -m phytograph agent-files`` writes both:

* ``AGENTS.md``: facts generated from the installed package (version, engine
  version, where its skill lives), then the body of the shipped ``SKILL.md``,
  with its ``references/`` links pointing at the installed files. The skill is
  the one source; nothing here is a hand-kept copy.
* ``CLAUDE.md``: only ``@AGENTS.md``, which makes Claude Code read it even when
  another ``CLAUDE.md`` exists in a directory above the project.

A file is rewritten only while its FIRST line is the marker below. Once the
user deletes that line the file is theirs and is never touched again. Set
``PHYTOGRAPH_AGENT_FILES=0`` to make the command write nothing, for a harness
that runs it unconditionally. (The same design as Helios's
``generate_agent_files.cmake``; Python has no configure step, so it is a
command rather than something that runs on its own.)

``python -m phytograph skills install`` copies the shipped skill folders into
an agent's skills directory instead, for harnesses that load skills.
"""
from __future__ import annotations

import os
import re
import shutil
from pathlib import Path
from typing import Dict, List, Optional, Tuple

from ._version import EXPECTED_BACKEND_VERSION, __version__

MARKER = "<!-- phytograph-managed-file"
MARKER_LINE = (f"{MARKER}: regenerated by \"python -m phytograph agent-files\". "
               "Delete this line to keep your own edits. -->")
DOCS_URL = "https://plantsimulationlab.github.io/Phytograph/guide/scripting/"
ENV_OPT_OUT = "PHYTOGRAPH_AGENT_FILES"
STAMP = ".phytograph-managed"


def _skills_dir() -> Path:
    return Path(__file__).resolve().parent / "skills"


def disabled_by_env() -> bool:
    v = os.environ.get(ENV_OPT_OUT)
    return v is not None and v.strip().lower() in ("0", "off", "false", "no", "")


def skill_body(skill_dir: Path) -> str:
    """SKILL.md without its frontmatter, with relative links made absolute."""
    text = (skill_dir / "SKILL.md").read_text(encoding="utf-8")
    m = re.match(r"^---\n.*?\n---\n", text, re.S)
    if not m:
        raise ValueError(f"{skill_dir / 'SKILL.md'} has no frontmatter")
    body = text[m.end():].lstrip("\n")

    def absolute(link: re.Match) -> str:
        target = (skill_dir / link.group(2)).resolve()
        return f"[{link.group(1)}]({target.as_posix()})"
    return re.sub(r"\[([^\]]+)\]\((references/[^)]+)\)", absolute, body)


def agents_md() -> str:
    skill_dir = _skills_dir() / "phytograph"
    head = [
        MARKER_LINE, "",
        "# Using the phytograph Python package", "",
        f"- Installed: `phytograph` {__version__} (processing engine {EXPECTED_BACKEND_VERSION}).",
        f"- Its agent skill and reference files: `{skill_dir.as_posix()}`.",
        f"- Guide: {DOCS_URL}",
        f"- If `python -c \"import phytograph; print(phytograph.__version__)\"` is not "
        f"{__version__}, run `python -m phytograph agent-files` again: this file describes "
        f"{__version__}.",
        "- `help(pg.Cloud.<tool>)` gives each tool's parameters, units and defaults.", "",
    ]
    # The skill's own H1 is replaced by the heading above.
    body = re.sub(r"^# [^\n]*\n+", "", skill_body(skill_dir), count=1)
    return "\n".join(head) + "\n" + body.rstrip("\n") + "\n"


def claude_md() -> str:
    return f"{MARKER_LINE}\n\n@AGENTS.md\n"


def write_managed(path: Path, content: str, *, dry_run: bool = False) -> str:
    """'written', 'unchanged' or 'user-owned' (exists without the marker at byte 0)."""
    if path.exists():
        existing = path.read_text(encoding="utf-8")
        if not existing.startswith(MARKER):
            return "user-owned"
        if existing == content:
            return "unchanged"
    if not dry_run:
        path.write_text(content, encoding="utf-8")
    return "written"


def write_agent_files(project: Path, *, dry_run: bool = False) -> Tuple[Dict[str, str], List[str]]:
    """Write AGENTS.md and CLAUDE.md into ``project``. Returns each file's
    status and any notes for the user."""
    project = Path(project)
    if not project.is_dir():
        raise NotADirectoryError(f"{project} is not a directory")
    status = {
        "AGENTS.md": write_managed(project / "AGENTS.md", agents_md(), dry_run=dry_run),
        "CLAUDE.md": write_managed(project / "CLAUDE.md", claude_md(), dry_run=dry_run),
    }
    notes = []
    if status["CLAUDE.md"] == "user-owned" and status["AGENTS.md"] != "user-owned":
        # Claude Code reads AGENTS.md only when there is no CLAUDE.md.
        if "@AGENTS.md" not in (project / "CLAUDE.md").read_text(encoding="utf-8"):
            notes.append(f"{project / 'CLAUDE.md'} is your own file, so Claude Code will not read "
                         "AGENTS.md. Add the line '@AGENTS.md' to it.")
    if status["AGENTS.md"] == "user-owned":
        notes.append(f"{project / 'AGENTS.md'} is your own file (no marker line); it was left "
                     "alone. Delete it, or paste in the output of --stdout, to update it.")
    return status, notes


def install_skills(dest: Path, *, force: bool = False,
                   names: Optional[List[str]] = None) -> Dict[str, str]:
    """Copy the shipped skill folders into ``dest`` (e.g. ``.claude/skills``).
    A folder this command installed carries a stamp file and is replaced; any
    other existing folder is refused unless ``force``."""
    src_root = _skills_dir()
    dest = Path(dest)
    out = {}
    for src in sorted(p for p in src_root.iterdir() if (p / "SKILL.md").is_file()):
        if names and src.name not in names:
            continue
        target = dest / src.name
        if target.exists():
            stamped = (target / STAMP).is_file()
            if not stamped and not force:
                raise FileExistsError(
                    f"{target} exists and was not installed by phytograph; pass --force to "
                    "replace it, or remove it.")
            shutil.rmtree(target)
            out[src.name] = "replaced"
        else:
            out[src.name] = "installed"
        shutil.copytree(src, target, ignore=shutil.ignore_patterns("__pycache__", ".*"))
        (target / STAMP).write_text(
            f"phytograph {__version__}: installed by \"python -m phytograph skills install\". "
            "Re-run it after upgrading phytograph. Delete this file to keep your own edits.\n",
            encoding="utf-8")
    return out
